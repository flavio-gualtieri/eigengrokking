#!/usr/bin/env python3
# scripts/bench_spectral_settings.py

"""
Wall time of the post-hoc spectral statistics per checkpoint
(scripts/spectral_from_checkpoints.py) for the p=91 sweep model, over the
candidate (m, k) settings and both curvature operators (H, Gauss-Newton G).
CUDA-synchronised, median of repeats after a warm-up; the Hessian is of the
loss on the full training set (2484 examples). Timing doesn't depend on the
weights' values, so the model is freshly initialised and the inputs synthetic.

    python scripts/bench_spectral_settings.py --out reports/spectral_benchmark.md
"""

from __future__ import annotations

import argparse
import platform
import statistics
import time
from pathlib import Path

import torch

from eigengrok.config import ExperimentConfig
from eigengrok.hessian.operators import CurvatureOperators
from eigengrok.hessian.snapshot import operator_stats
from eigengrok.tasks.registry import get_task

SETTINGS = [(20, 10), (20, 20), (30, 10), (30, 20), (50, 8), (100, 100)]  # candidates, the current default, the old production setting
CONFIG = Path("configs/mod91_wd_sweep_beta2_0.98.yaml")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=Path("reports/spectral_benchmark.md"))
    parser.add_argument("--repeats", type=int, default=5)
    args = parser.parse_args()

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    cfg = ExperimentConfig.from_yaml(CONFIG)
    task = get_task(cfg)
    model = task.build_model(device).eval()
    n_train = round(cfg.train_frac * cfg.modulus ** 2)
    g = torch.Generator().manual_seed(0)
    x = torch.randint(0, cfg.modulus, (n_train, 3), generator=g)
    x[:, 2] = cfg.modulus  # the "=" token
    x, y = x.float().to(device), torch.randint(0, cfg.modulus, (n_train,), generator=g).to(device)
    loss = lambda logits, labels: task.compute_training_loss(logits, labels, device)  # noqa: E731

    def timed(fn) -> float:
        fn()  # warm-up (also builds the cached gradient graph on first use)
        times = []
        for _ in range(args.repeats):
            if device.type == "cuda":
                torch.cuda.synchronize()
            start = time.perf_counter()
            fn()
            if device.type == "cuda":
                torch.cuda.synchronize()
            times.append(time.perf_counter() - start)
        return statistics.median(times)

    rows = []
    for m, k in SETTINGS:
        ops = CurvatureOperators(model, x, y, loss)
        t = {op: timed(lambda op=op: operator_stats(ops, op, m=m, k=k, probe_seed=0))
             for op in ("hessian", "gauss_newton")}
        rows.append((m, k, t["hessian"], t["gauss_newton"]))
        print(f"m={m} k={k}: H {t['hessian']:.2f} s, G {t['gauss_newton']:.2f} s")

    name = torch.cuda.get_device_name(device) if device.type == "cuda" else platform.processor() or "CPU"
    lines = [
        "# Post-hoc spectral cost per checkpoint",
        "",
        f"Generated by `python scripts/bench_spectral_settings.py`. Device: {name}; torch {torch.__version__}. "
        f"Model and training-set size of `{CONFIG}` ({sum(p.numel() for p in model.parameters()):,} parameters, "
        f"Hessian on all {n_train} training examples); median of {args.repeats} repeats after a warm-up.",
        "",
        "| m | k | H (s) | G (s) | H + G (s) |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| {m} | {k} | {th:.2f} | {tg:.2f} | {th + tg:.2f} |" for m, k, th, tg in rows]
    args.out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
