#!/usr/bin/env python3
# scripts/compare_sweeps.py

"""
The sweep rerun (AdamW betas (0.9, 0.98)) against the original sweep (betas
(0.9, 0.999)), same model, data, weight decays, init scales and seeds:
onset, memorization, grokking, post-grokking collapses and final accuracy,
per (init, wd) and pooled per init scale.

    python scripts/compare_sweeps.py

Milestones: eigengrok/analysis/milestones.py, via each sweep's per-run table
(scripts/sweep_summary.py writes sweep_milestones.csv). Only settings present
in both are compared, so the comparison is valid while the rerun is still
running. Intervals: 95% percentile bootstrap over seeds; pooled ratios
resample seeds within each weight decay.

Writes reports/sweep_comparison.csv and reports/sweep_comparison.md.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from eigengrok.analysis.bootstrap import bootstrap_ci, bootstrap_ratio_ci

OLD = Path("reports/sweep_milestones.csv")
NEW = Path("reports/sweep_beta2_0.98/sweep_milestones.csv")


def gmean(x: np.ndarray, axis: int = 0) -> np.ndarray:
    return np.exp(np.mean(np.log(x), axis=axis))


def _ci(lo_hi, fmt="{:.2f}") -> str:
    return "--" if not np.isfinite(lo_hi[0]) else f"[{fmt.format(lo_hi[0])}, {fmt.format(lo_hi[1])}]"


def compare(old: pd.DataFrame, new: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    keys = sorted(set(map(tuple, old[["init", "wd"]].to_numpy())) & set(map(tuple, new[["init", "wd"]].to_numpy())))
    cells = []
    for init, wd in keys:
        o = old[(old["init"] == init) & np.isclose(old["wd"], wd)]
        n = new[(new["init"] == init) & np.isclose(new["wd"], wd)]
        cells.append({
            "init": init, "wd": wd, "n_old": len(o), "n_new": len(n),
            "onset_ratio": gmean(n["t_onset"]) / gmean(o["t_onset"]),
            "onset_ratio_ci": bootstrap_ratio_ci(n["t_onset"], o["t_onset"], gmean),
            "t_mem_median_old": o["t_mem"].median(), "t_mem_median_new": n["t_mem"].median(),
            "collapses_old": o["n_collapses"].mean(), "collapses_new": n["n_collapses"].mean(),
            "collapses_new_ci": bootstrap_ci(n["n_collapses"], np.mean),
            "final_ok_old": (o["final_test_acc"] >= 0.95).mean(), "final_ok_new": (n["final_test_acc"] >= 0.95).mean(),
        })
    cells = pd.DataFrame(cells)

    pooled = []
    for init in sorted(cells["init"].unique()):
        wds = cells.loc[cells["init"] == init, "wd"].to_numpy()
        o = old[(old["init"] == init) & old["wd"].isin(wds)]
        n = new[(new["init"] == init) & new["wd"].isin(wds)]
        pooled.append({
            "init": init, "n_wd": len(wds), "n_old": len(o), "n_new": len(n),
            "onset_ratio": gmean(n["t_onset"]) / gmean(o["t_onset"]),
            "onset_ratio_ci": bootstrap_ratio_ci(n["t_onset"], o["t_onset"], gmean, strata_num=n["wd"], strata_den=o["wd"]),
            "collapse_ratio": n["n_collapses"].mean() / o["n_collapses"].mean(),
            "collapse_ratio_ci": bootstrap_ratio_ci(n["n_collapses"], o["n_collapses"], np.mean,
                                                    strata_num=n["wd"], strata_den=o["wd"]),
            "zero_collapse_runs_new": int((n["n_collapses"] == 0).sum()),
            "t_mem_ratio": n["t_mem"].median() / o["t_mem"].median(),
            "t_mem_ratio_ci": bootstrap_ratio_ci(n["t_mem"], o["t_mem"], np.median, strata_num=n["wd"], strata_den=o["wd"]),
        })
    return cells, pd.DataFrame(pooled)


def markdown(cells: pd.DataFrame, pooled: pd.DataFrame, n_new_runs: int) -> str:
    L = ["# Sweep rerun (beta2 = 0.98) against the original sweep (beta2 = 0.999)", "",
         "Generated by `python scripts/compare_sweeps.py` from `reports/sweep_milestones.csv` (original) and "
         f"`reports/sweep_beta2_0.98/sweep_milestones.csv` (rerun, {n_new_runs} runs so far). Same model, data, "
         "weight decays, init scales and seeds; only Adam's beta2 differs. Only settings present in both sweeps are "
         "compared. Onset ratio: geometric mean of t_onset, rerun / original. Intervals: 95% bootstrap over seeds.", "",
         "## Pooled per init scale (baseline: the original sweep)", "",
         "| init | weight decays | runs (orig / rerun) | onset ratio [CI] | collapses / run ratio [CI] | rerun runs with no collapse | median t_mem ratio [CI] |",
         "|---|---|---|---|---|---|---|"]
    for _, r in pooled.iterrows():
        L.append(f"| {r['init']:g} | {r['n_wd']} | {r['n_old']} / {r['n_new']} | {r['onset_ratio']:.2f} {_ci(r['onset_ratio_ci'])} | "
                 f"{r['collapse_ratio']:.3f} {_ci(r['collapse_ratio_ci'], '{:.3f}')} | {r['zero_collapse_runs_new']} of {r['n_new']} | "
                 f"{r['t_mem_ratio']:.2f} {_ci(r['t_mem_ratio_ci'])} |")
    L += ["", "## Per setting", "",
          "| init | wd | runs (orig / rerun) | onset ratio [CI] | median t_mem (orig / rerun) | collapses / run (orig / rerun [CI]) | final test acc >= 0.95 (orig / rerun) |",
          "|---|---|---|---|---|---|---|"]
    for _, r in cells.iterrows():
        L.append(f"| {r['init']:g} | {r['wd']:.2f} | {r['n_old']} / {r['n_new']} | {r['onset_ratio']:.2f} {_ci(r['onset_ratio_ci'])} | "
                 f"{r['t_mem_median_old']:,.0f} / {r['t_mem_median_new']:,.0f} | {r['collapses_old']:.1f} / "
                 f"{r['collapses_new']:.1f} {_ci(r['collapses_new_ci'], '{:.1f}')} | "
                 f"{r['final_ok_old']:.0%} / {r['final_ok_new']:.0%} |")
    L.append("")
    return "\n".join(L)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--old", type=Path, default=OLD)
    parser.add_argument("--new", type=Path, default=NEW)
    parser.add_argument("--out-dir", type=Path, default=Path("reports"))
    args = parser.parse_args()

    old, new = pd.read_csv(args.old), pd.read_csv(args.new)
    cells, pooled = compare(old, new)
    cells.to_csv(args.out_dir / "sweep_comparison.csv", index=False, float_format="%.6g")
    (args.out_dir / "sweep_comparison.md").write_text(markdown(cells, pooled, len(new)))
    print(f"Wrote {args.out_dir / 'sweep_comparison.csv'} and {args.out_dir / 'sweep_comparison.md'}")


if __name__ == "__main__":
    main()
