#!/usr/bin/env python3
# scripts/compute_budget.py

"""
Compute used by the jobs behind the reported results, from SLURM accounting
(`sacct`), so it must run on the cluster that ran them:

    python scripts/compute_budget.py      # writes reports/compute_budget.md

Covers the jobs in JOBS. The original sweep (reports/wd_sweep_accuracy_curves.csv)
predates this record; its job IDs were not kept.
"""

from __future__ import annotations

import argparse
import statistics
import subprocess
from pathlib import Path

JOBS = [  # (job id, what it did)
    ("31656339", "collapse pilot: 4 arms x 10 seeds, 30k steps"),
    ("31672515", "sweep rerun (beta2 = 0.98): 240 runs, 150k steps, checkpoints pruned to the Phase 2 grid"),
    ("31706205", "Hessian + Gauss-Newton spectra at every kept checkpoint of the 240 runs (m=20, k=20)"),
    ("31696838", "spectral cost benchmark"),
    ("31744779", "post-processing: curves, summaries, forecasting audit, figures (CPU)"),
]


def _seconds(elapsed: str) -> int:
    days, _, hms = elapsed.rpartition("-")
    h, m, s = (int(x) for x in hms.split(":"))
    return (int(days) if days else 0) * 86400 + h * 3600 + m * 60 + s


def job_usage(job: str) -> dict:
    out = subprocess.run(["sacct", "-j", job, "-X", "-n", "-P", "--format=JobID,State,Elapsed,AllocTRES"],
                         capture_output=True, text=True, check=True).stdout
    tasks = [line.split("|") for line in out.strip().splitlines() if line]
    done = [t for t in tasks if t[1] == "COMPLETED"]
    secs = [_seconds(t[2]) for t in done]
    gpus = [int(next((kv.split("=")[1] for kv in t[3].split(",") if kv.startswith("gres/gpu=")), "0")) for t in done]
    cpus = [int(next((kv.split("=")[1] for kv in t[3].split(",") if kv.startswith("cpu=")), "0")) for t in done]
    return {"tasks": len(tasks), "completed": len(done),
            "gpu_hours": sum(s * g for s, g in zip(secs, gpus)) / 3600,
            "cpu_hours": sum(s * c for s, c in zip(secs, cpus)) / 3600,
            "median_task_min": statistics.median(secs) / 60 if secs else float("nan")}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=Path("reports/compute_budget.md"))
    args = parser.parse_args()

    rows = [(job, what, job_usage(job)) for job, what in JOBS]
    lines = ["# Compute budget", "",
             "Generated by `python scripts/compute_budget.py` from SLURM accounting (completed tasks only). "
             "GPU: NVIDIA A100 80GB. CPU-hours count the cores allocated, not the cores used.", "",
             "| job | what | tasks (completed) | median task (min) | GPU-hours | CPU core-hours |", "|---|---|---|---|---|---|"]
    for job, what, u in rows:
        lines.append(f"| {job} | {what} | {u['tasks']} ({u['completed']}) | {u['median_task_min']:.1f} | "
                     f"{u['gpu_hours']:.1f} | {u['cpu_hours']:.0f} |")
    total_gpu = sum(u["gpu_hours"] for _, _, u in rows)
    lines += ["", f"Total: {total_gpu:.1f} GPU-hours. The original sweep (240 runs at beta2 = 0.999) is not included: "
              "its job IDs were not recorded.", ""]
    args.out.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
